#!/usr/bin/env swift
// Build PS4 Linux Loader PKG (OpenOrbis). Installs toolchain under repo if missing.
import Foundation

let repo = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let loaderDir = repo.appendingPathComponent("ps4-linux-launcher-app/linux-loader", isDirectory: true)
let toolchainDir = repo.appendingPathComponent("vendor/OpenOrbis/PS4Toolchain", isDirectory: true)
let toolchainURL =
    "https://github.com/OpenOrbis/OpenOrbis-PS4-Toolchain/releases/download/v0.5.3/toolchain-llvm-18.2.zip"

@discardableResult
func run(_ launchPath: String, _ args: [String], cwd: URL? = nil, env: [String: String]? = nil, live: Bool = true) throws -> Int32 {
    let task = Process()
    task.executableURL = URL(fileURLWithPath: launchPath)
    task.arguments = args
    if let cwd { task.currentDirectoryURL = cwd }
    var e = ProcessInfo.processInfo.environment
    e["PATH"] = "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
    env?.forEach { e[$0.key] = $0.value }
    task.environment = e
    if live {
        task.standardOutput = FileHandle.standardOutput
        task.standardError = FileHandle.standardError
    } else {
        let pipe = Pipe()
        task.standardOutput = pipe
        task.standardError = pipe
    }
    try task.run()
    task.waitUntilExit()
    return task.terminationStatus
}

func step(_ n: Int, _ total: Int, _ message: String) {
    print("\n=== [\(n)/\(total)] \(message) ===")
    fflush(stdout)
}

/// Pre-release 0.7.x + monotonic APP_VER and VERSION in param.sfo (both must change for updates).
/// Logic mirrored in tools/PS4LinuxTools/Sources/PS4LinuxCore/PkgVersioning.swift — keep in sync; run `swift tools/ps4-linux-test.swift`.
func bumpPkgVersion(loaderDir: URL, bump: Bool) throws -> (display: String, sonyAppVer: String, masterVersion: String, buildLabel: String) {
    let versionFile = loaderDir.appendingPathComponent("PKG_VERSION")
    let buildFile = loaderDir.appendingPathComponent("PKG_BUILD_NUM")
    let displayRaw = (try? String(contentsOf: versionFile, encoding: .utf8)) ?? "0.7.0"
    let buildRaw = try? String(contentsOf: buildFile, encoding: .utf8)

    var parts = displayRaw.trimmingCharacters(in: .whitespacesAndNewlines)
        .split(separator: ".").compactMap { Int($0) }
    while parts.count < 3 { parts.append(0) }
    if parts[0] == 0 && parts[1] < 7 { parts = [0, 7, 0] }

    var buildNum = 70
    if let buildRaw,
       let parsed = Int(buildRaw.trimmingCharacters(in: .whitespacesAndNewlines)), parsed >= 70 {
        buildNum = parsed
    }
    if bump {
        parts[2] += 1
        buildNum += 1
    } else if buildNum < 70 {
        buildNum = 70
    }

    let display = "\(parts[0]).\(parts[1]).\(parts[2])"
    let buildLabel = String(buildNum)
    let sonyAppVer = String(format: "%02d.%02d", buildNum / 100, buildNum % 100)
    let masterVersion = String(format: "01.%d", buildNum)

    try display.write(to: versionFile, atomically: true, encoding: .utf8)
    try "\(buildNum)\n".write(to: buildFile, atomically: true, encoding: .utf8)
    try sonyAppVer.write(to: loaderDir.appendingPathComponent(".pkg-app-ver"), atomically: true, encoding: .utf8)
    try masterVersion.write(to: loaderDir.appendingPathComponent(".pkg-master-ver"), atomically: true, encoding: .utf8)

    let header = loaderDir.appendingPathComponent("include/BuildVersion.h")
    try """
    #pragma once
    // Generated by tools/ps4-linux-launcher-build.swift — do not edit.
    #define PS4_LINUX_PKG_VERSION "\(display)"
    #define PS4_LINUX_PKG_BUILD "\(buildLabel)"
    #define PS4_LINUX_PKG_APP_VER "\(sonyAppVer)"

    """.write(to: header, atomically: true, encoding: .utf8)
    return (display, sonyAppVer, masterVersion, buildLabel)
}

func ensureToolchain() throws {
    let marker = toolchainDir.appendingPathComponent("bin/macos/PkgTool.Core")
    if FileManager.default.fileExists(atPath: marker.path) {
        print("OpenOrbis toolchain: already present")
        fflush(stdout)
        return
    }
    step(1, 4, "Download OpenOrbis PS4 Toolchain")
    try FileManager.default.createDirectory(at: toolchainDir.deletingLastPathComponent(), withIntermediateDirectories: true)
    let zip = toolchainDir.deletingLastPathComponent().appendingPathComponent("OpenOrbis-PS4-Toolchain.zip")
    if try run("/usr/bin/curl", ["-fL", "--progress-bar", "-o", zip.path, toolchainURL]) != 0 {
        throw NSError(domain: "ps4-linux-launcher-build", code: 1, userInfo: [NSLocalizedDescriptionKey: "Toolchain download failed"])
    }
    if FileManager.default.fileExists(atPath: toolchainDir.path) {
        try FileManager.default.removeItem(at: toolchainDir)
    }
    if try run("/usr/bin/unzip", ["-q", "-o", zip.path, "-d", toolchainDir.deletingLastPathComponent().path]) != 0 {
        throw NSError(domain: "ps4-linux-launcher-build", code: 2, userInfo: [NSLocalizedDescriptionKey: "Toolchain unzip failed"])
    }
    let innerTar = toolchainDir.deletingLastPathComponent().appendingPathComponent("toolchain-llvm-18.tar.gz")
    if FileManager.default.fileExists(atPath: innerTar.path) {
        if FileManager.default.fileExists(atPath: toolchainDir.path) {
            try FileManager.default.removeItem(at: toolchainDir)
        }
        if try run("/usr/bin/tar", ["-xzf", innerTar.path, "-C", toolchainDir.deletingLastPathComponent().path]) != 0 {
            throw NSError(domain: "ps4-linux-launcher-build", code: 3, userInfo: [NSLocalizedDescriptionKey: "Toolchain tar extract failed"])
        }
        let parent = toolchainDir.deletingLastPathComponent()
        let entries = try FileManager.default.contentsOfDirectory(at: parent, includingPropertiesForKeys: nil)
        if let extracted = entries.first(where: { $0.lastPathComponent == "PS4Toolchain" && $0.hasDirectoryPath }) {
            let dest = toolchainDir
            if FileManager.default.fileExists(atPath: dest.path) {
                try FileManager.default.removeItem(at: dest)
            }
            try FileManager.default.createDirectory(at: dest.deletingLastPathComponent(), withIntermediateDirectories: true)
            try FileManager.default.moveItem(at: extracted, to: dest)
        }
    }
}

func ensureLLVM() throws -> (cc: String, cxx: String, ld: String) {
    let brewPaths = [
        ("/opt/homebrew/opt/llvm/bin/clang", "/opt/homebrew/opt/llvm/bin/clang++", "/opt/homebrew/opt/llvm/bin/ld.lld"),
        ("/usr/local/opt/llvm/bin/clang", "/usr/local/opt/llvm/bin/clang++", "/usr/local/opt/llvm/bin/ld.lld"),
    ]
    for c in brewPaths where FileManager.default.fileExists(atPath: c.0) {
        print("LLVM: using Homebrew at \(c.0)")
        fflush(stdout)
        return (c.0, c.1, c.2)
    }

    let llvmRoot = repo.appendingPathComponent("vendor/llvm-macos", isDirectory: true)
    let clang = llvmRoot.appendingPathComponent("bin/clang")
    if FileManager.default.fileExists(atPath: clang.path) {
        print("LLVM: using cached vendor/llvm-macos")
        fflush(stdout)
        return (clang.path, llvmRoot.appendingPathComponent("bin/clang++").path, llvmRoot.appendingPathComponent("bin/ld.lld").path)
    }

    let url =
        "https://github.com/llvm/llvm-project/releases/download/llvmorg-18.1.8/clang+llvm-18.1.8-arm64-apple-macos11.tar.xz"
    step(2, 4, "Download LLVM 18 (clang + ld.lld)")
    let tar = repo.appendingPathComponent("vendor/clang+llvm-18.1.8-arm64-apple-macos11.tar.xz")
    try FileManager.default.createDirectory(at: tar.deletingLastPathComponent(), withIntermediateDirectories: true)
    if try run("/usr/bin/curl", ["-fL", "--progress-bar", "-o", tar.path, url]) != 0 {
        throw NSError(domain: "ps4-linux-launcher-build", code: 10, userInfo: [NSLocalizedDescriptionKey: "LLVM download failed — run: brew install llvm"])
    }
    if try run("/usr/bin/tar", ["-xJf", tar.path, "-C", tar.deletingLastPathComponent().path]) != 0 {
        throw NSError(domain: "ps4-linux-launcher-build", code: 11, userInfo: [NSLocalizedDescriptionKey: "LLVM extract failed"])
    }
    let parent = tar.deletingLastPathComponent()
    let entries = try FileManager.default.contentsOfDirectory(at: parent, includingPropertiesForKeys: nil)
    if let extracted = entries.first(where: { $0.lastPathComponent.hasPrefix("clang+llvm") && $0.hasDirectoryPath }) {
        if FileManager.default.fileExists(atPath: llvmRoot.path) {
            try FileManager.default.removeItem(at: llvmRoot)
        }
        try FileManager.default.moveItem(at: extracted, to: llvmRoot)
    }
    return (clang.path, llvmRoot.appendingPathComponent("bin/clang++").path, llvmRoot.appendingPathComponent("bin/ld.lld").path)
}

/// Human-readable PKG name (CONTENT_ID inside unchanged). Example: PS4-Linux-v0.7.5-b75-APP0075.pkg
func versionedPkgFileName(display: String, buildLabel: String, sonyAppVer: String) -> String {
    let appDigits = sonyAppVer.replacingOccurrences(of: ".", with: "")
    return "PS4-Linux-v\(display)-b\(buildLabel)-APP\(appDigits).pkg"
}

func canonicalContentPkgName() -> String {
    "IV0000-CSTP00002_00-PS4LINUXL0700000.pkg"
}

/// Copy OpenOrbis output to versioned filename; drop older PS4-Linux-v*.pkg in the same folder.
func publishVersionedPkg(loaderDir: URL, display: String, buildLabel: String, sonyAppVer: String) throws -> URL {
    let canonical = loaderDir.appendingPathComponent(canonicalContentPkgName())
    guard FileManager.default.fileExists(atPath: canonical.path) else {
        throw NSError(
            domain: "ps4-linux-launcher-build", code: 20,
            userInfo: [NSLocalizedDescriptionKey: "Missing \(canonical.lastPathComponent) after make"]
        )
    }
    let versionedName = versionedPkgFileName(display: display, buildLabel: buildLabel, sonyAppVer: sonyAppVer)
    let versioned = loaderDir.appendingPathComponent(versionedName)
    if FileManager.default.fileExists(atPath: versioned.path) {
        try FileManager.default.removeItem(at: versioned)
    }
    try FileManager.default.copyItem(at: canonical, to: versioned)

    let entries = try FileManager.default.contentsOfDirectory(at: loaderDir, includingPropertiesForKeys: [.contentModificationDateKey])
    for url in entries where url.pathExtension == "pkg" {
        let name = url.lastPathComponent
        if name.hasPrefix("PS4-Linux-v"), name != versionedName {
            try? FileManager.default.removeItem(at: url)
        }
    }
    return versioned
}

do {
    let args = CommandLine.arguments
    let shouldBump = !args.contains("--no-bump")
    let (pkgVersion, sonyAppVer, masterVersion, buildLabel) = try bumpPkgVersion(loaderDir: loaderDir, bump: shouldBump)
    print("PKG pre-release: v\(pkgVersion)  APP_VER=\(sonyAppVer)  VERSION(master)=\(masterVersion)  build #\(buildLabel)")
    if !shouldBump {
        print("  (--no-bump: version unchanged except BuildVersion.h refresh)")
    }

    step(1, 4, "Check OpenOrbis toolchain")
    try ensureToolchain()
    step(2, 4, "Check LLVM cross-compiler")
    let clang = try ensureLLVM()
    let makeEnv: [String: String] = [
        "OO_PS4_TOOLCHAIN": toolchainDir.path,
        "CC": clang.cc,
        "CXX": clang.cxx,
        "LD": clang.ld,
        "PKG_LABEL": pkgVersion,
        "MASTER_VERSION": masterVersion,
        "APP_VER_VALUE": sonyAppVer,
    ]
    step(3, 4, "make clean && make all (linux-loader PKG)")
    print("  OO_PS4_TOOLCHAIN=\(toolchainDir.path)")
    print("  CC=\(clang.cc)")
    print("  PKG_LABEL=\(pkgVersion) MASTER_VERSION=\(masterVersion) APP_VER=\(sonyAppVer)")
    fflush(stdout)
    let status = try run("/usr/bin/make", ["-C", loaderDir.path, "clean", "all"], env: makeEnv)
    if status != 0 {
        fputs("make failed (\(status))\n", stderr)
        exit(Int32(status))
    }
    step(4, 4, "Verify PKG output")
    let versioned = try publishVersionedPkg(
        loaderDir: loaderDir, display: pkgVersion, buildLabel: buildLabel, sonyAppVer: sonyAppVer
    )
    let pkg = versioned
    if FileManager.default.fileExists(atPath: pkg.path) {
        print("Built (install this file): \(pkg.path)")
        print("  CONTENT_ID pkg: \(loaderDir.appendingPathComponent(canonicalContentPkgName()).path)")
        let tool = toolchainDir.appendingPathComponent("bin/macos/PkgTool.Core").path
        let sfo = loaderDir.appendingPathComponent("sce_sys/param.sfo")
        if FileManager.default.fileExists(atPath: tool),
           FileManager.default.fileExists(atPath: sfo.path) {
            let check = Process()
            check.executableURL = URL(fileURLWithPath: tool)
            check.arguments = ["sfo_listentries", sfo.path]
            let pipe = Pipe()
            check.standardOutput = pipe
            check.standardError = pipe
            try check.run()
            check.waitUntilExit()
            let out = String(data: pipe.fileHandleForReading.readDataToEndOfFile(), encoding: .utf8) ?? ""
            if !out.contains("APP_VER") {
                fputs("ERROR: param.sfo has no APP_VER — Package Installer will say already installed.\n", stderr)
                exit(1)
            }
            if !out.contains(sonyAppVer) {
                fputs("ERROR: param.sfo APP_VER mismatch (expected \(sonyAppVer))\n\(out)\n", stderr)
                exit(1)
            }
            if !out.contains(masterVersion) {
                fputs("ERROR: param.sfo VERSION mismatch (expected \(masterVersion))\n\(out)\n", stderr)
                exit(1)
            }
            if out.contains("APP_VER :") && out.contains("VERSION :") {
                if let appLine = out.split(separator: "\n").first(where: { $0.contains("APP_VER :") }),
                   let verLine = out.split(separator: "\n").first(where: { $0.contains("VERSION :") && !$0.contains("APP_VER") }),
                   appLine == verLine {
                    fputs("ERROR: APP_VER must differ from VERSION (Sony / Orbis rule)\n", stderr)
                    exit(1)
                }
            }
        }
        print("Install: Package Installer → `/data/pkg/\(pkg.lastPathComponent)`")
        print("         GoldHEN → disable Background Installation if updates are blocked.")
    } else {
        print("Build finished — check linux-loader/PS4-Linux-v*.pkg")
    }
} catch {
    fputs("Error: \(error.localizedDescription)\n", stderr)
    exit(1)
}
